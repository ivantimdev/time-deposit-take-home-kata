-- ASSUMPTION A11: the assignment's camelCase logical names map to snake_case physical names.
-- ASSUMPTION A14: integrity, non-negative days and balances, positive amounts and the foreign key
-- index are enforced here, by the database, not by application code.

CREATE TABLE time_deposits (
    -- "by default" so that seed data may give explicit ids
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ASSUMPTION A12: mirrors the PlanType codes; a new plan needs a migration extending this list.
    plan_type VARCHAR(32)   NOT NULL CHECK (plan_type IN ('basic', 'student', 'premium')),
    days      INTEGER       NOT NULL CHECK (days >= 0),
    -- zero, not strictly positive: a deposit may be emptied by withdrawals
    balance   NUMERIC(19,2) NOT NULL CHECK (balance >= 0)
);

CREATE TABLE withdrawals (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_deposit_id INTEGER       NOT NULL REFERENCES time_deposits (id) ON DELETE RESTRICT,
    amount          NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    -- named as the assignment names it
    date            DATE          NOT NULL
);

-- PostgreSQL does not index foreign key columns; this serves the foreign key lookups.
CREATE INDEX withdrawals_time_deposit_id_idx ON withdrawals (time_deposit_id);
